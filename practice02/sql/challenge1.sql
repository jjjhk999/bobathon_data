-- Scenario 2 challenge 1 and demo. Run once against an empty BOB_SQL_LAB schema.
-- All merchants, payments and dates are synthetic.
CREATE TABLE BOB_SQL_LAB.MERCHANT (
    MERCHANT_ID INTEGER NOT NULL PRIMARY KEY,
    MERCHANT_NAME VARCHAR(40) NOT NULL,
    REGION VARCHAR(10) NOT NULL,
    ACTIVE_YN CHAR(1) NOT NULL CHECK (ACTIVE_YN IN ('Y', 'N'))
);

CREATE TABLE BOB_SQL_LAB.PAYMENT (
    PAYMENT_ID INTEGER NOT NULL PRIMARY KEY,
    MERCHANT_ID INTEGER NOT NULL,
    PAYMENT_TS TIMESTAMP(6) NOT NULL,
    PAYMENT_STATUS VARCHAR(10) NOT NULL
        CHECK (PAYMENT_STATUS IN ('APPROVED', 'DECLINED', 'REVERSED')),
    AMOUNT DECIMAL(12, 2) NOT NULL CHECK (AMOUNT >= 0),
    CONSTRAINT PAYMENT_MERCHANT_FK
        FOREIGN KEY (MERCHANT_ID) REFERENCES BOB_SQL_LAB.MERCHANT (MERCHANT_ID)
);

