           ELSE 'INCHEON'
       END,
       CASE WHEN MOD(MERCHANT_ID, 9) = 0 THEN 'N' ELSE 'Y' END
FROM MERCHANT_NUMBERS
WHERE MERCHANT_ID <= 600;

